<?php

namespace App\Modules\AiAgent\Services;

use App\Modules\Foundation\Services\Settings;
use App\Modules\Messaging\Models\Conversation;
use App\Modules\Messaging\Models\Message;

/**
 * تعليمات الوكيل وتاريخ المحادثة.
 *
 * **لا كتالوج في التعليمات ولا سعر ولا رصيد.** المبدأ الأول («مصدر الحقيقة
 * قاعدة البيانات لا النموذج») لا يُصان بالأمر وحده: نموذجٌ أُعطي قائمة أسعارٍ
 * في تعليماته سيذكرها من ذاكرته بعد عشر رسائل ولن يستدعي أداة. فالطريق الوحيد
 * إلى أرقام المتجر هو الأداة، ولا نسخة ثانية منها هنا.
 *
 * واسم المتجر وحده يُقرأ من الإعدادات — تعريفٌ لا بيانات.
 */
class SalesAgentPrompt
{
    /** تعليمات النظام. */
    public function system(): string
    {
        $store = Settings::get('store.name', 'المتجر');

        return <<<PROMPT
        أنت موظّف مبيعات في «{$store}»، تردّ على الزبائن عبر واتساب.

        # الأسلوب
        - اكتب بالعربية بلهجة فلسطينية بسيطة ومهذّبة.
        - رسائل قصيرة: سطران أو ثلاثة. هذه محادثة واتساب لا رسالة بريد.
        - سؤال واحد في الرسالة الواحدة. لا تسأل عن الصنف والكمية والعنوان معًا.
        - لا رموز تنسيق (لا نجوم ولا عناوين). واتساب لا يعرضها.

        # قاعدة مطلقة: لا رقم من عندك
        لا تذكر سعرًا ولا توفّرًا ولا مدّة توصيل ولا رسوم شحن ولا رقم طلب إلّا
        إذا جاءك من نتيجة أداة في هذه المحادثة نفسها.
        - لا تحسب سعرًا بنفسك ولا تجمع ولا تضرب. اطلب السعر من الأداة.
        - لا تعتمد على رقم ذكرته سابقًا في المحادثة؛ الأسعار والأرصدة تتغيّر.
        - إن رجعت الأداة خطأً أو نتيجة فارغة: لا تخمّن. اسأل الزبون سؤالًا
          يوضّح طلبه، أو حوّل إلى موظفة.
        - لا تَعِد بخصم ولا بعرض ولا بهدية ولا بموعد تسليم محدّد.

        # الأصناف
        لا تبِع صنفًا لم ترجعه أداة البحث. الأصناف غير الجاهزة لا تظهر لك
        أصلًا؛ فإن سأل الزبون عن صنف لم تجده، قل إنك ستتأكّد وحوّل إلى موظفة.

        # الطلب
        الطلب خطوتان: مسودّة، ثم تأكيد.
        - اجمع أولًا: الصنف والكمية، ثم الاسم، ثم المدينة والمنطقة، ثم العنوان.
        - قبل التأكيد اعرض الملخّص كاملًا (الأصناف والكميات والمجموع والشحن)
          واطلب موافقة صريحة.
        - لا تؤكّد إلّا بعد كلمة واضحة من الزبون مثل «أكّد» أو «موافق» أو
          «ماشي». «شكرًا» و«تمام» ليستا موافقة على الشراء.

        # متى تحوّل إلى موظفة
        - شكوى أو غضب أو طلب استرجاع أو إلغاء.
        - سؤال عن طلب سابق أو عن مبلغ مدفوع.
        - طلب خصم أو سعر جملة أو تعامل تاجر.
        - سؤال خارج البيع، أو سؤال لم تستطع الإجابة عنه بأداة.
        - تكرّر عدم الفهم مرّتين.
        عند التحويل: اعتذر بجملة قصيرة وقل إن موظفة ستتابع معه. لا تخترع سببًا.

        # الشفافية
        إن سألك الزبون: هل أنت إنسان؟ — أجب بصدق أنك مساعد آليّ وأن موظفة
        متاحة متى أراد.
        PROMPT;
    }

    /**
     * تاريخ المحادثة بصيغة واجهة النموذج.
     *
     * الواردة `user` والصادرة `assistant` — بما فيها ما كتبته موظفة بيدها:
     * من زاوية الزبون كلُّه صوتُ المتجر، وفصلُه يجعل الوكيل يناقض ما قيل له
     * قبل قليل.
     *
     * والمتتاليات من الدور نفسه تُدمج، والتاريخ يبدأ من رسالة زبون: الواجهة
     * ترفض ما عدا ذلك، ورفضُها يقع وقت الردّ لا وقت الكتابة.
     *
     * @return array<int, array<string, mixed>>
     */
    public function history(Conversation $conversation): array
    {
        $limit = (int) config('ai_agent.history_messages', 20);

        $messages = $conversation->messages()
            ->latest('id')->limit($limit)->get()->reverse()->values();

        $turns = [];

        foreach ($messages as $message) {
            $text = $this->text($message);

            if ($text === '') {
                continue;
            }

            $role = $message->direction === Message::IN ? 'user' : 'assistant';
            $last = array_key_last($turns);

            if ($last !== null && $turns[$last]['role'] === $role) {
                $turns[$last]['content'] .= "\n".$text;

                continue;
            }

            $turns[] = ['role' => $role, 'content' => $text];
        }

        while ($turns !== [] && $turns[0]['role'] !== 'user') {
            array_shift($turns);
        }

        return $turns;
    }

    /**
     * نصّ الرسالة كما يقرأه النموذج.
     *
     * الوسائط لا تُمرَّر — لا يقرأ الوكيل صورةً في هذه المرحلة. لكن **وجودها
     * يُذكر**: زبونٌ أرسل صورة صنفٍ وسأل «هذا بكم؟» يبدو سؤاله بلا معنى إن
     * حُذفت الصورة من التاريخ، فيردّ الوكيل ردًّا مرتبكًا بدل أن يحوّل.
     */
    private function text(Message $message): string
    {
        $body = trim((string) $message->body);

        if ($message->type !== 'text' && $message->media_path !== null) {
            $note = '[أرسل الزبون '.$this->mediaLabel((string) $message->type).']';

            return $body === '' ? $note : $note.' '.$body;
        }

        return $body;
    }

    private function mediaLabel(string $type): string
    {
        return match ($type) {
            'image' => 'صورة',
            'video' => 'مقطع فيديو',
            'audio' => 'رسالة صوتية',
            'document' => 'ملفًّا',
            'location' => 'موقعًا',
            default => 'مرفقًا',
        };
    }
}
