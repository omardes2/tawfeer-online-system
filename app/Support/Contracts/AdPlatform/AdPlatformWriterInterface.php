<?php

namespace App\Support\Contracts\AdPlatform;

use App\Support\Integrations\AdPlatform\AdSetState;
use Illuminate\Support\Collection;

/**
 * عقد **الكتابة** إلى منصّة الإعلانات — منفصلٌ عن عقد القراءة عمدًا.
 *
 * الفصل ليس ترتيبًا للملفات: محرّك القراءة يعمل برمزٍ صلاحيتُه `ads_read`، وهذا
 * يعمل برمزٍ آخر صلاحيتُه `ads_management`. فخطأٌ في المزامنة الليلية — أو ثغرةٌ
 * في مسار الاستيراد — **لا يملك أصلًا القدرة على إنفاق مال**. ولو وُسّع العقد
 * الأول بدل إضافة هذا لصار رمزٌ واحد يقرأ ويصرف، وسقط الحاجز.
 *
 * وحدود هذا العقد مقصودة: **يوقف ويشغّل ويعدّل ميزانية مجموعةٍ قائمة، ولا
 * يُنشئ حملةً ولا إعلانًا ولا مادّةً إبداعية**. إنشاء الحملات مرحلةٌ تالية بعقدٍ
 * ثالث — لأن الإنشاء يحتاج صفحةً ومادّةً ومراجعةً من المنصّة، وأخطاؤه لا تُلتقط
 * بالتراجع كما تُلتقط أخطاء الإيقاف.
 *
 * ولا يُستدعى محرّك مباشرةً من متحكّم أو خدمة أعمال — فقط عبر `AdPlatformManager`.
 */
interface AdPlatformWriterInterface
{
    /** اسم المحرّك للسجلّات والواجهة. */
    public function name(): string;

    /**
     * هل المحرّك مضبوط وجاهز للكتابة؟
     *
     * الضبط هنا يشترط **رمز كتابة مستقلًّا**: وجود رمز القراءة وحده لا يجعل
     * المحرّك جاهزًا للصرف. وغيرُ المضبوط يتوقّف بهدوء ولا يرمي — فالمهمّة
     * الليلية لا يجوز أن تفشل على نظامٍ لم تُفتح له صلاحية الكتابة بعد.
     */
    public function isConfigured(): bool;

    /**
     * الحالة الحيّة لمجموعاتٍ إعلانية بمعرّفاتها.
     *
     * تُقرأ قبل كل قرار: الميزانية قد تكون تغيّرت يدويًّا من لوحة المنصّة، وقرارٌ
     * مبنيٌّ على رقمٍ من أمس يضاعف الخطأ بدل أن يصحّحه.
     *
     * @param  array<int, string>  $externalIds
     * @return Collection<string, AdSetState> مفهرسةً بالمعرّف الخارجي
     */
    public function adSets(array $externalIds): Collection;

    /** إيقاف مجموعة إعلانية — الفعل الوحيد الذي لا يزيد الصرف أبدًا. */
    public function pause(string $adSetId): void;

    /** إعادة تشغيل مجموعة أوقفها الطيّار — لا يُستدعى إلا بقرار إنسان. */
    public function resume(string $adSetId): void;

    /**
     * ضبط الميزانية اليومية بعملة الحساب الإعلاني.
     *
     * بعملة الحساب لا بالشيكل ولا بالدولار افتراضًا: المنصّة تفرض عملة الحساب،
     * وتحويلٌ في هذه الطبقة يعني أن خطأً في سعر الصرف يصير خطأً في المبلغ
     * المصروف فعلًا. العملة تُقرأ من `AdSetState` وتُعرض كما هي.
     */
    public function setDailyBudget(string $adSetId, float $amount): void;
}
