<?php

namespace App\Support\Contracts\Pixel;

use App\Support\Integrations\Pixel\ConversionEvent;

/**
 * عقد قياس التحويلات من الخادم (المبدأ 12 — عقدٌ ومحرّكات).
 *
 * وجودُه شرطٌ لهدف «الشراء عبر الموقع»: المنصّة لا تُحسِّن على ما لا تراه. وبلا
 * حدث شراءٍ يصلها، تختار جمهورًا **ينقر** لا جمهورًا **يشتري** — فتصرف الميزانية
 * كاملةً وتبدو الحملة «تعمل».
 *
 * ومن الخادم لا من المتصفّح وحده: مانعات الإعلانات وiOS تُسقط جزءًا كبيرًا من
 * أحداث المتصفّح، والشراء أهمّ من أن يُترك لها. والأهمّ هنا أن مسار الإتمام
 * **محميّ لا يُمسّ** (تكامل التوصيل)، فحدث الشراء يُرسَل من حدثٍ داخلي بعد
 * إنشاء الطلب — بلا سطرٍ واحد في شيفرة الإتمام.
 */
interface ConversionTrackerInterface
{
    /** اسم المحرّك للسجلّات والواجهة. */
    public function name(): string;

    /** هل المحرّك مضبوط؟ غيرُ المضبوط يمرّ بهدوء ولا يرمي. */
    public function isConfigured(): bool;

    /**
     * إرسال حدث تحويل واحد.
     *
     * يرمي عند فشل النداء ليعيد الطابور المحاولة — الحدث المفقود لا يُعوَّض،
     * والمنصّة تقبل إعادة الإرسال بالمعرّف نفسه بلا ازدواج.
     */
    public function track(ConversionEvent $event): void;
}
